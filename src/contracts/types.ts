/**
 * Hour-by-hour external environment slice across the 72-Hour Crisis
 * Combining LRO LOLA horizon eclipse at Shackleton Connecting Ridge (89.47°S, 222.6°E)
 * with the historical August 4, 1972 Carrington-class Solar Particle Event (SPE).
 */
export interface CrisisHourEnvironment {
  hour: number; // 0 to 72
  phaseLabel: string;
  /** Sun elevation above local Shackleton ridge horizon in degrees (-1.2° shadowed to +1.54° sunlit) */
  sunElevationAboveRidgeDeg: number;
  /** Fraction of solar array illuminated [0.0 to 1.0] based on LOLA horizon mask */
  solarIlluminationFactor: number;
  /** Unshielded >100 MeV proton flux (pfu) from Aug 1972 SPE reconstruction */
  protonFluxPfu: number;
  /** Unshielded free-space / surface BFO dose rate in mSv/hr (GCR baseline + SPE spike) */
  unshieldedDoseRateMsvPerHr: number;
  /** External surface temperature in Kelvin (220 K sunlit peak vs 40 K shadowed crater wall) */
  surfaceTempK: number;
  alertLevel: 'nominal' | 'watch' | 'warning' | 'critical';
  eventHeadline: string;
}

/**
 * Player-controlled valve & breaker state on the Crisis Flight Deck.
 * "Every Kilogram of Water Works Twice": Total system water is conserved (minus Sabatier CH4 hydrogen bleed unless recovered).
 */
export interface ValveAndBreakerControls {
  /** Liters (1 L = 1 kg) of water pumped into the Storm Shelter Jacket Bladder (0 to 500 L) */
  shelterWallWaterLiters: number;
  /** OGA Water Electrolysis Stack throttle (0 to 100%) — splits H2O into O2 + 2H2 at 4.5 kWh/kg O2 */
  electrolysisThrottlePct: number;
  /** Sabatier Reactor toggle — reacts CO2 + 4H2 -> CH4(vented) + 2H2O (bleeds Hydrogen unless pyrolysis active!) */
  sabatierActive: boolean;
  /** Methane Pyrolysis & PSR Ice Melter loop closure toggle — recovers H2 from CH4 at +3.8 kW power cost */
  methanePyrolysisActive: boolean;
  /** Hydroponic Salad & Dwarf Wheat Bay irrigation + LED PAR lighting throttle (0 to 100%) */
  hydroponicsThrottlePct: number;
  /** Thermal Radiator / Heater loop throttle (0 to 100%) */
  thermalLoopPct: number;
  /** Crew posture: nominal operations vs huddled inside the Water-Wall Storm Shelter */
  crewInStormShelter: boolean;
}

/**
 * Instantaneous hourly flow rates for the ECLSS & EPS simulation
 */
export interface HourlyMassAndPowerFlows {
  solarGeneratedKw: number;
  totalLoadKw: number;
  netBatteryKw: number;
  /** O2 generated by OGA electrolysis + hydroponic photosynthesis (kg/hr) */
  o2GeneratedKgPerHr: number;
  /** O2 consumed by 4 crewmembers (kg/hr) */
  o2ConsumedKgPerHr: number;
  /** CO2 exhaled by 4 crewmembers (kg/hr) */
  co2ProducedKgPerHr: number;
  /** CO2 scrubbed by Sabatier + Hydroponics + LiOH Mailbox (kg/hr) */
  co2ScrubbedKgPerHr: number;
  /** H2O consumed by electrolysis + hydroponic transpiration (L/hr) */
  waterConsumedLPerHr: number;
  /** H2O recovered from crew respiration/hygiene + Sabatier condensation (L/hr) */
  waterRecoveredLPerHr: number;
  /** Hydrogen mass lost overboard via Sabatier CH4 venting (equiv L/hr of H2O lost permanently!) */
  sabatierWaterBleedEquivLPerHr: number;
  /** Shielded radiation dose rate inside crew location (mSv/hr) */
  shieldedDoseRateMsvPerHr: number;
  /** Shielding attenuation percentage [0-99%] provided by Water-Wall Jacket + hull */
  shieldAttenuationPct: number;
  /** Areal density of the water-wall jacket in g/cm^2 */
  waterWallArealDensityGPerCm2: number;
  /** Net caloric output from hydroponic dwarf wheat/lettuce tray (kcal/hr) */
  foodProducedKcalPerHr: number;
  /** Crew caloric burn (kcal/hr) */
  foodConsumedKcalPerHr: number;
}

export interface CrisisGameState {
  hour: number; // 0 to 72
  maxHours: number; // 72
  crewCount: number; // 4 astronauts
  /** Regenerative Fuel Cell / Battery reserve (kWh), max 180 kWh */
  batteryKwh: number;
  maxBatteryKwh: number;
  /** Total conserved liquid water inventory in the outpost (L), partitioned between Shelter Wall & Active ECLSS Tank */
  totalSystemWaterLiters: number;
  /** Available liquid water in the active ECLSS / Hydroponic supply tank (L) = totalSystemWaterLiters - shelterWallWaterLiters */
  activeTankWaterLiters: number;
  /** Cabin breathable O2 reserve (kg) */
  cabinO2Kg: number;
  /** Cabin CO2 partial pressure (mmHg) — nominal 2.0 mmHg, >4.0 mmHg cognitive impairment, >7.5 mmHg critical */
  cabinCo2MmHg: number;
  /** Cumulative crew BFO radiation dose (mSv) — NASA 30-day limit 250 mSv; cadet mission warning at 25 mSv, fail at 75 mSv */
  cumulativeRadiationMsv: number;
  /** Harvestable + stored caloric buffer (kcal) */
  foodBufferKcal: number;
  /** Crop health in the Hydroponic Bay (0 to 100%) — wilts if activeTankWaterLiters < 200 L or hydroponicsThrottlePct < 25% */
  cropHealthPct: number;
  /** Internal cabin temperature (°C) — nominal 21.5°C, safe [15°C, 30°C] */
  cabinTempC: number;
  /** Cumulative water-equivalent liters lost to space via Sabatier CH4 venting */
  cumulativeWaterBleedLiters: number;
  controls: ValveAndBreakerControls;
  lastFlows: HourlyMassAndPowerFlows;
  eventLog: { hour: number; message: string; severity: 'info' | 'warn' | 'danger' }[];
  status: 'running' | 'survived' | 'failed';
  failureReason?: string;
  failureCitationId?: CitationId;
}
